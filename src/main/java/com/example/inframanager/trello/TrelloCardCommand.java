package com.example.inframanager.trello;

import com.example.inframanager.pullrequest.PullRequestRef;
import com.fasterxml.jackson.annotation.JsonIgnoreProperties;

/**
 * То, что лежит в {@code outbound_task.payload} для задачи TRELLO: желаемое состояние
 * одной карточки, а не шаг, который надо выполнить.
 *
 * <p>Описание целевого состояния вместо «создать» или «переместить» делает задачу
 * безопасной для повтора и для обработки не по порядку — применив её дважды, получим
 * ту же карточку в том же списке.
 */
@JsonIgnoreProperties(ignoreUnknown = true)
public record TrelloCardCommand(

        PullRequestRef pullRequest,

        String boardId,

        /** Null означает «оставить карточку на месте и лишь обновить её содержимое». */
        String moveToListName,

        /**
         * Куда попадает карточка, которой ещё нет. Null у команд, которые правят уже
         * существующую карточку и создавать ничего не должны.
         */
        String createInListName,

        String title,

        String description,

        /** Записывается в связку, когда известен; null, если в ветке нет ключа. */
        String issueKey,

        /**
         * Имена меток; отсутствующие создаются на доске. Null оставляет метки карточки
         * как есть — именно этого хочет сверка.
         */
        java.util.List<String> labels,

        /**
         * Цвет обложки — того самого фона, которым карточка видна на доске. Null оставляет
         * обложку как есть: так поступают сверка и суточный проход, которым до вида
         * карточки дела нет. {@link #NO_COVER} — снять обложку; репозиторий, которому
         * цвет не настроен, должен оставлять карточки без фона, а не хранить вечно тот,
         * что настроили когда-то.
         */
        String coverColor,

        /**
         * Идентификаторы автора, от наиболее точного к менее точному. Сопоставляются
         * с существующими участниками доски; в отличие от меток, участников создать
         * нельзя, поэтому автор без учётной записи в Trello просто оставляет карточку
         * без исполнителя.
         */
        java.util.List<String> memberCandidates,

        /**
         * Задачи ревью как пункты чек-листа. Null означает «не трогать чек-лист» —
         * именно это нужно сверке и всему, что не знает о задачах; пустой список,
         * наоборот, означает «задач нет», и чек-лист убирается с карточки.
         */
        java.util.List<ChecklistItem> checklist,

        /**
         * {@link Boolean#TRUE} — убрать карточку в архив; null — не трогать. Это не
         * педантизм: {@code closed: false} Trello понимает как «достать из архива», и
         * команда, говорящая так на всякий случай, возвращает на доску всё, что с неё
         * убрали руками. Сказать «не в архиве» не хочет никто — в архив карточку
         * отправляет один лишь удалённый пул-реквест.
         */
        Boolean archive,

        /**
         * Момент, которым датируется попадание карточки в колонку: он становится её
         * датой начала, если эта команда колонку и правда меняет. Именно началом, а не
         * сроком: срок в прошлом Trello красит красным, а этот момент в прошлом всегда.
         * Null — дату не трогать; так поступают сверка и суточный проход, которые
         * карточку из состояния в состояние не переводят, а лишь поправляют доску.
         *
         * <p>Это время события, а не время закрытия пул-реквеста, которым живёт
         * {@link #closedAt}: срок отвечает на вопрос «когда карточка стала такой», а у
         * «ушла в ревью» или «попросили правок» момента в Bitbucket просто нет — там
         * даже {@code updatedDate} на смену вердикта ревьюера не сдвигается.
         */
        java.time.Instant listEnteredAt,

        /**
         * Когда пул-реквест влили или отклонили. Записывается в связку, откуда суточный
         * проход и узнаёт возраст карточки; null — событие не о закрытом пул-реквесте.
         * Ничего сам по себе не приказывает: это факт, а не команда.
         */
        java.time.Instant closedAt,

        /**
         * Не null — отметить карточку выполненной, проставив ей этот срок. Срок здесь не
         * украшение: без него Trello хранит отметку, но не показывает её ни на карточке,
         * ни на доске. Null — статус карточки не трогать.
         */
        java.time.Instant completeAsOf) {

    /** Явное «без фона» — в отличие от null, который значит «обложку не трогать». */
    public static final String NO_COVER = "";

    @JsonIgnoreProperties(ignoreUnknown = true)
    public record ChecklistItem(String name, boolean done) {
    }
}
