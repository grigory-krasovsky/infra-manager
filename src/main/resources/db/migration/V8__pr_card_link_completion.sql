-- Когда карточка попала в свою колонку и когда её отметили выполненной.
--
-- updated_at на роль «давно ли лежит» не годится: его двигает любое обновление
-- содержимого, и карточка, которой всего лишь освежили заголовок, выглядела бы
-- только что переехавшей.
ALTER TABLE pr_card_link
    ADD COLUMN list_entered_at TIMESTAMPTZ,
    ADD COLUMN completed_at    TIMESTAMPTZ;

-- Истории перемещений у уже заведённых карточек нет, и ближайшее к ней — время
-- последнего обновления: для давно влитого пул-реквеста это и есть момент вливания.
-- Значит, первый же проход отметит выполненным всё, что пролежало в колонке влитых
-- дольше недели, — этого от него и ждут.
UPDATE pr_card_link
SET list_entered_at = updated_at
WHERE current_list_id IS NOT NULL;
