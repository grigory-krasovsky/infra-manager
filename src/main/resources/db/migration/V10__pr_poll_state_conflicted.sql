-- Мешают ли конфликты влить пул-реквест.
--
-- Конфликт появляется и исчезает не от действий в самом пул-реквесте, а от чужих
-- мержей в целевую ветку: ни версия пул-реквеста, ни его ветка, ни статусы
-- ревьюеров при этом не меняются. Без этой колонки сравнивать было бы не с чем, и
-- опрос такого изменения попросту не заметил бы.
--
-- NULL здесь значит "не знаем": у закрытого пул-реквеста, у не опрошенного ещё и
-- у того, о чьём мерже Bitbucket промолчал. Отличать это от "конфликтов нет"
-- обязательно — иначе заминка Bitbucket снимала бы значок с карточки.
ALTER TABLE pr_poll_state
    ADD COLUMN conflicted BOOLEAN;
