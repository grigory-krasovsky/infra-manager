-- Неделю до «выполнено» отсчитываем от факта в Bitbucket, а не от переезда карточки.
--
-- list_entered_at отвечал на вопрос «давно ли карточка лежит в колонке», и вопрос
-- оказался не тем: в колонку карточка попадает не тогда, когда влили пул-реквест.
-- Она отстаёт на время простоя сервиса, а перетащенная руками — на сколько угодно.
-- Считать надо от момента, когда пул-реквест влили или отклонили, и этот момент
-- присылает сам Bitbucket.
ALTER TABLE pr_card_link
    ADD COLUMN closed_at TIMESTAMPTZ;

-- У карточек, заведённых раньше, момента закрытия взять неоткуда: по закрытому
-- пул-реквесту событий больше не приходит, и переспросить некого. Ближайшее к нему —
-- время последнего обновления карточки: для давно влитого PR это и есть вливание.
-- Значение перетрётся настоящим, как только по этому пул-реквесту придёт хоть одно
-- событие, — так что открытым карточкам приблизительная дата не повредит.
UPDATE pr_card_link
SET closed_at = COALESCE(list_entered_at, updated_at)
WHERE current_list_id IS NOT NULL;

ALTER TABLE pr_card_link
    DROP COLUMN list_entered_at;
