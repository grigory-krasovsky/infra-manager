-- Отпечаток списка задач пул-реквеста ("blocker comments").
--
-- Задачи не двигают карточку — колонку определяет только статус ревьюера, — но
-- попадают в неё чек-листом. Чтобы чек-лист не устаревал, опрос должен замечать,
-- что задачу добавили, закрыли или удалили, а само по себе это не меняет ни версию
-- пул-реквеста, ни ветку, ни статусы ревьюеров: сравнивать больше не с чем.
--
-- Хранится хеш, а не список: задач бывает много, а колонке достаточно отвечать на
-- вопрос "то же самое или уже нет".
ALTER TABLE pr_poll_state
    ADD COLUMN task_digest VARCHAR(64);
