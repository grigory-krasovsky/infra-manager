-- Незакрытые задачи пул-реквеста ("blocker comments" в терминах Bitbucket).
--
-- Хранятся рядом с остальным наблюдением, потому что меняются независимо от него:
-- задачу открывают и закрывают, не трогая ни статус ревьюера, ни версию PR, ни
-- ветку. Без отдельной колонки опрос такое изменение не замечает вовсе.
--
-- NULL у строк, заведённых раньше: он читается как "задач не было", и первый же
-- проход опроса заменит его настоящим числом.
ALTER TABLE pr_poll_state
    ADD COLUMN open_tasks INTEGER;
