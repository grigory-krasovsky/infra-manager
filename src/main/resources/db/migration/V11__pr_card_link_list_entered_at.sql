-- Момент, когда карточка попала в нынешнюю колонку, — тот самый, что показан на ней
-- датой начала.
--
-- Столбец с этим именем уже удаляла V9, и по делу: отсчитывать от него неделю до
-- «выполнено» было неправильно, потому что он отвечает на вопрос о доске, а не о
-- пул-реквесте. Здесь он нужен ровно для вопроса о доске — «с какого момента карточка
-- лежит здесь», — и на роль срока больше не претендует: неделя по-прежнему считается
-- от closed_at.
--
-- Хранится он у нас, а не только в Trello, потому что команда карточке описывает её
-- желаемое состояние целиком. Дата, живущая лишь на карточке, из этого состояния
-- выпадала: стёртую руками нечем было бы восстановить, а перерисовать доску после
-- раскатки — нечем проставить.
ALTER TABLE pr_card_link
    ADD COLUMN list_entered_at TIMESTAMPTZ;

-- У карточек закрытых пул-реквестов момент попадания в конечную колонку — это и есть
-- закрытие: туда их кладёт pr:merged или pr:declined, и датируются они им же. У
-- остальных взять его неоткуда, и приблизительного значения тут лучше не выдумывать:
-- пустая дата просто не показывается, а неверная врёт. Первый же переезд её проставит.
UPDATE pr_card_link
SET list_entered_at = closed_at
WHERE closed_at IS NOT NULL;
